#!/usr/bin/env node
// motifjs-i18n keys <messages.json> [out.d.ts]
// Writes a `MessageKey` union from the keys of one catalog, to hand to createI18n<MessageKey>().
import { readFileSync, writeFileSync } from 'node:fs';

const [command, input, output = 'keys.d.ts'] = process.argv.slice(2);

if (command !== 'keys' || !input) {
  console.error('Usage: motifjs-i18n keys <messages.json> [out.d.ts]');
  process.exit(1);
}

function flatten(node, prefix = '') {
  return Object.entries(node).flatMap(([key, value]) =>
    typeof value === 'string' ? [prefix + key] : flatten(value, `${prefix}${key}.`),
  );
}

const keys = flatten(JSON.parse(readFileSync(input, 'utf8'))).sort();
const body = keys.map((k) => `  | ${JSON.stringify(k)}`).join('\n');
writeFileSync(output, `// Generated by motifjs-i18n keys from ${input}. Do not edit.\nexport type MessageKey =\n${body};\n`);
console.log(`${keys.length} keys -> ${output}`);
